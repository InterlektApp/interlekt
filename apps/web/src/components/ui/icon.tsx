export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName | string;
  className?: string;
  size?: number;
  strokeWidth?: number;
  /** Accessible label. When omitted the icon is decorative. */
  label?: string;
}

/** One icon, sized like the design system (18px / 1.5 stroke by default). */
export function Icon({ name, className, size = 18, strokeWidth = 1.5, label }: IconProps) {
  const Cmp = ICONS[name];
  if (!Cmp) return null;
  return (
    <Cmp
      className={cn("icon shrink-0", className)}
      width={size}
      height={size}
      strokeWidth={strokeWidth}
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
    />
  );
}
